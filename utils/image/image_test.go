package image

import (
	"strings"
	"testing"
)

// 1x1 BMP（24 位，自底向上）：验证解码器注册后 BMP 可压缩重编码为 PNG data URL
var tinyBmp = []byte{
	0x42, 0x4d, 0x46, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x36, 0x00, 0x00, 0x00,
	0x28, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x00,
	0x18, 0x00, 0x00, 0x00, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x13, 0x0b, 0x00, 0x00,
	0x13, 0x0b, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xff, 0x00,
	0x00, 0x00, 0x00, 0x00, 0x00,
}

func TestCompressImageBmp(t *testing.T) {
	out, mime, err := CompressImage(tinyBmp, "bmp", DefaultImageMaxSize)
	if err != nil {
		t.Fatalf("BMP compress failed: %v", err)
	}
	if mime != "image/png" {
		t.Fatalf("BMP should re-encode to PNG, got %s", mime)
	}
	if !strings.HasPrefix(string(out[0:1]), "\x89") {
		t.Fatalf("expect PNG magic, got %x", out[0])
	}
}
